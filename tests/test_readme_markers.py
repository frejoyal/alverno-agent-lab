"""The result markers of README.md (ADR 0015 « Banc d'essai »).

Each bench rewrites only its own marker family: ``RESULTS`` (``alverno bench``),
``RESULTS-HR`` (``alverno hr bench``), ``RESULTS-SVC`` (``alverno service bench``) and
``RESULTS-MAINT`` (``alverno maint bench``). Every family appears exactly once per
language, the opening marker before the closing one, each on a line of its own, French in
the French part and English in the English part, in that order. Rewriting one family
leaves every other byte of the README identical, the other three families included.
``tests/test_quality_frozen.py`` keeps its own fixture-README check unchanged.
"""

from __future__ import annotations

import pytest

from alverno_lab.cli import MAINT_MARKERS, SVC_MARKERS, replace_marked_block

from .conftest import REPO_ROOT

README = REPO_ROOT / "README.md"
FAMILIES: tuple[str, ...] = ("RESULTS", "RESULTS-HR", "RESULTS-SVC", "RESULTS-MAINT")
LANGS: tuple[str, ...] = ("FR", "EN")
ENGLISH_HEADING = "## English"


def _text() -> str:
    return README.read_text(encoding="utf-8")


def _lines(text: str) -> list[str]:
    return [line.strip() for line in text.split("\n")]


def _markers(family: str, lang: str) -> tuple[str, str]:
    return f"<!-- {family}:{lang} -->", f"<!-- /{family}:{lang} -->"


def _masked(text: str, family: str) -> str:
    """``text`` with the inside of each block of ``family`` replaced by one placeholder."""
    lines = text.split("\n")
    kept: list[str] = []
    inside = False
    for line in lines:
        bare = line.strip()
        if any(bare == _markers(family, lang)[1] for lang in LANGS):
            inside = False
        if not inside:
            kept.append(line)
        if any(bare == _markers(family, lang)[0] for lang in LANGS):
            inside = True
            kept.append("<masked>")
    return "\n".join(kept)


def _block(text: str, family: str, lang: str) -> str:
    """The lines between the two markers of one block, as written."""
    bare = _lines(text)
    start, end = _markers(family, lang)
    return "\n".join(text.split("\n")[bare.index(start) + 1 : bare.index(end)])


def _rewritten(text: str, family: str) -> str:
    for lang in LANGS:
        text = replace_marked_block(text, f"{family}:{lang}", f"new table {family}:{lang}")
    return text


@pytest.mark.parametrize("lang", LANGS)
@pytest.mark.parametrize("family", FAMILIES)
def test_each_family_appears_once_per_language_in_order(family: str, lang: str) -> None:
    text = _text()
    bare = _lines(text)
    start, end = _markers(family, lang)
    assert bare.count(start) == 1, start
    assert bare.count(end) == 1, end
    assert bare.index(start) < bare.index(end), start
    # A marker counts only alone on its line: no other line may quote it.
    assert text.count(start) == 1 and text.count(end) == 1, start


@pytest.mark.parametrize("family", FAMILIES)
def test_each_language_sits_in_its_part_of_the_readme(family: str) -> None:
    bare = _lines(_text())
    english = bare.index(ENGLISH_HEADING)
    french_end = bare.index(_markers(family, "FR")[1])
    english_start = bare.index(_markers(family, "EN")[0])
    assert french_end < english < english_start, family


def test_the_families_follow_each_other_in_both_languages() -> None:
    bare = _lines(_text())
    for lang in LANGS:
        positions = [bare.index(_markers(family, lang)[0]) for family in FAMILIES]
        assert positions == sorted(positions), lang
        # Each module 3 block comes right after the previous family, with no other
        # family between.
        for before, after in (("RESULTS-HR", "RESULTS-SVC"), ("RESULTS-SVC", "RESULTS-MAINT")):
            end = bare.index(_markers(before, lang)[1])
            start = bare.index(_markers(after, lang)[0])
            between = bare[end + 1 : start]
            assert not [line for line in between if line.startswith("<!-- ")], (lang, after)


def test_the_cli_writes_the_module_3_families() -> None:
    assert SVC_MARKERS == ("RESULTS-SVC:FR", "RESULTS-SVC:EN")
    assert MAINT_MARKERS == ("RESULTS-MAINT:FR", "RESULTS-MAINT:EN")


@pytest.mark.parametrize("lang", LANGS)
def test_the_maintenance_blocks_were_written_by_the_bench(lang: str) -> None:
    """Exit criterion, point 5 (ADR 0015): the blocks come from ``alverno maint bench``
    (step I10), with the table, the 3b dataset digest and the bench signature."""
    inside = [line for line in _block(_text(), "RESULTS-MAINT", lang).split("\n") if line]
    signature = {
        "FR": "Généré par `alverno maint bench` ; ne pas modifier à la main.",
        "EN": "Generated by `alverno maint bench`; do not hand-edit.",
    }[lang]
    assert inside[-1] == signature, lang
    assert inside[0].startswith("| "), lang
    assert any("`data/eval/maint_gold.jsonl`" in line for line in inside), lang


@pytest.mark.parametrize("family", FAMILIES)
def test_rewriting_one_family_leaves_every_other_byte_identical(family: str) -> None:
    before = _text()
    after = _rewritten(before, family)
    assert after != before, family
    assert _masked(after, family) == _masked(before, family), family
    for lang in LANGS:
        assert f"new table {family}:{lang}" in after, (family, lang)
    for name in FAMILIES:
        for lang in LANGS:
            start, end = _markers(name, lang)
            assert _lines(after).count(start) == 1 and _lines(after).count(end) == 1, start
            if name != family:
                assert _block(after, name, lang) == _block(before, name, lang), (family, name)


@pytest.mark.parametrize("family", ["RESULTS-SVC", "RESULTS-MAINT"])
def test_a_rewrite_is_stable_when_repeated(family: str) -> None:
    once = _rewritten(_text(), family)
    assert _rewritten(once, family) == once
